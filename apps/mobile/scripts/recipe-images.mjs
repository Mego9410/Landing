// Rebuilds src/data/recipeImages.ts from the photos in assets/recipes. Each photo is named after its recipe id
// (assets/recipes/<id>.webp). Run after adding or replacing a photo: node scripts/recipe-images.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ids = readdirSync(join(root, "assets/recipes"))
  .filter((f) => f.endsWith(".webp"))
  .map((f) => f.slice(0, -5))
  .sort();

const lines = ids.map((id) => `  ${JSON.stringify(id)}: require("../../assets/recipes/${id}.webp"),`);
writeFileSync(
  join(root, "src/data/recipeImages.ts"),
  `// Generated by scripts/recipe-images.mjs from assets/recipes. Don't edit by hand.
import type { ImageSourcePropType } from "react-native";

/** A photo for each recipe, by recipe id. Photos are illustrative, generated with ChatGPT. */
export const RECIPE_IMAGES: Record<string, ImageSourcePropType> = {
${lines.join("\n")}
};
`,
);
console.log(`${ids.length} recipe photos`);
